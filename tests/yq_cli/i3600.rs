#[test]
fn test_json_sourced_merge_key_is_an_ordinary_key_3600() -> Result<()> {
    for (doc, filter, expected) in ROWS {
        let (stdout, code) = run_yq_stdin(filter, doc, &["-p", "json", "-o", "yaml", "-I", "0"])?;
        assert_eq!(
            (stdout.as_str(), code),
            (*expected, 0),
            "{filter} over {doc}"
        );
    }
    Ok(())
}

/// A JSON object key `<<` stays in JSON output, where yq drops it (rule 4(b): no data is lost).
#[test]
fn test_json_output_keeps_a_merge_spelled_key_3600() -> Result<()> {
    for (doc, filter, expected) in [
        (r#"{"<<":1,"a":2}"#, ".", "{\"<<\":1,\"a\":2}\n"),
        (
            r#"{"<<":1,"a":2}"#,
            ".zz = 1",
            "{\"<<\":1,\"a\":2,\"zz\":1}\n",
        ),
        (
            r#"{"a":{"<<":{"y":1},"b":2}}"#,
            ".a",
            "{\"<<\":{\"y\":1},\"b\":2}\n",
        ),
        // The string encoders keep it as well (yq: `"{\"a\":2}"`).
        (
            r#"{"<<":{"x":1},"a":2}"#,
            "to_json(0)",
            "\"{\\\"<<\\\":{\\\"x\\\":1},\\\"a\\\":2}\"\n",
        ),
    ] {
        let (stdout, code) = run_yq_stdin(filter, doc, &["-p", "json", "-o", "json", "-I", "0"])?;
        assert_eq!(
            (stdout.as_str(), code),
            (expected, 0),
            "{filter} over {doc}"
        );
    }
    Ok(())
}
