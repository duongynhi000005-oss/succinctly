//! #5018: a pipe stage that emits a `null` or a boolean after a bare caught-bind `foreach` UPDATE (`FE | null`), under
//! an EXTRACT that cannot move the register.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// jq's register after the inner `foreach`'s bind is the bound child, and a pipe stage that computes a value (`null`,
// `true`, `not`) does not move it, so the EXTRACT's `null`/boolean emission (or `.`, the state the stage left) is judged
// against that child whatever the stage's value. The binary judged it against the accumulator's register, so `try
// path(..) catch "C"` answered `"C"` where jq answers a path, and `[path(..)?]` dropped it.

/// #5018: `FE | null`, `FE | true`, `FE | not`, `try (FE | false)`, `(FE | null)?` and `FE | . == null` under a `null`,
/// `.`, `true` or `not` EXTRACT, over a root register's child that is `null`, `false` and a container; `[path(..)?]`
/// and `try path(..) catch`. Every row captured from `/usr/bin/jq` 1.7.1 (stdout, exit code), both routes.
#[test]
