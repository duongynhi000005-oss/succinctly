//! #5154: `--arg`, `--argjson`, `--slurpfile` and `--rawfile` apply in command-line order, and a name keeps its first value.

use anyhow::Result;

use crate::run_jq_full;

// jq's `main.c` walks the command line once, binding each of the four flags as it meets it, and skips a flag whose name is
// already bound before it reads or parses the value. succinctly applied them grouped by kind (every `--arg`, then every
// `--argjson`, ...) and let a later value replace an earlier one, so `$name` itself differed for a repeated name, and
// `$ARGS.named`'s key order for a mix of flags. The kinds come from argv (`named_flag_order`); each flag's values stay in
// clap's per-flag vectors.

/// #5154: repeated names across the four flags (the first value wins, a malformed or unreadable later duplicate is not read),
/// a mix of flags in `$ARGS.named`'s key order, and a flag value that spells another flag. Every expected output and exit
/// code captured from `/usr/bin/jq` 1.7.1.
#[test]
fn test_5154_named_args_apply_in_command_line_order_and_the_first_wins() -> Result<()> {
    let rows: &[(&[&str], &str, i32)] = &[
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--arg",
                r"a",
                r"2",
                r"$a,$ARGS.named",
            ],
            "\"1\"\n{\"a\":\"1\"}\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--argjson",
                r"a",
                r"2",
                r"$a,$ARGS.named",
            ],
            "\"1\"\n{\"a\":\"1\"}\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--argjson",
                r"a",
                r"1",
                r"--arg",
                r"a",
                r"2",
                r"$a,$ARGS.named",
            ],
            "1\n{\"a\":1}\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--argjson",
                r"j",
                r"1",
                r"--arg",
                r"a",
                r"2",
                r"$ARGS.named",
            ],
            "{\"j\":1,\"a\":\"2\"}\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"2",
                r"--argjson",
                r"j",
                r"1",
                r"$ARGS.named|keys_unsorted",
            ],
            "[\"a\",\"j\"]\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--slurpfile",
                r"s",
                r"/dev/null",
                r"--argjson",
                r"j",
                r"3",
                r"--rawfile",
                r"r",
                r"/dev/null",
                r"$ARGS.named|keys_unsorted",
            ],
            "[\"a\",\"s\",\"j\",\"r\"]\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--rawfile",
                r"r",
                r"/dev/null",
                r"--slurpfile",
                r"s",
                r"/dev/null",
                r"--arg",
                r"a",
                r"1",
                r"$ARGS.named|keys_unsorted",
            ],
            "[\"r\",\"s\",\"a\"]\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--slurpfile",
                r"a",
                r"/dev/null",
                r"$a",
            ],
            "\"1\"\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--slurpfile",
                r"a",
                r"/dev/null",
                r"--arg",
                r"a",
                r"1",
                r"$a",
            ],
            "[]\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--rawfile",
                r"a",
                r"/dev/null",
                r"--argjson",
                r"a",
                r"5",
                r"$a",
            ],
            "\"\"\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--argjson",
                r"a",
                r"{bad",
                r"$a",
            ],
            "\"1\"\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--slurpfile",
                r"a",
                r"/nonexistent",
                r"$a",
            ],
            "\"1\"\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--rawfile",
                r"a",
                r"/nonexistent",
                r"$a",
            ],
            "\"1\"\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--argjson",
                r"a",
                r"1",
                r"--argjson",
                r"a",
                r"bad",
                r"$a",
            ],
            "1\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--argjson",
                r"a",
                r"bad",
                r"--argjson",
                r"a",
                r"1",
                r"$a",
            ],
            "",
            2,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"b",
                r"2",
                r"--arg",
                r"a",
                r"1",
                r"$ARGS.named|keys_unsorted",
            ],
            "[\"b\",\"a\"]\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"$ARGS.named",
                r"--arg",
                r"a",
                r"2",
                r"--args",
                r"x",
            ],
            "{\"a\":\"1\"}\n",
            0,
        ),
        (
            &[r"-nc", r"--arg", r"--arg", r"v", r"$ARGS.named"],
            "{\"--arg\":\"v\"}\n",
            0,
        ),
        (
            &[
                r"-nc",
                r"--arg",
                r"a",
                r"1",
                r"--arg",
                r"b",
                r"2",
                r"--arg",
                r"a",
                r"3",
                r"$ARGS.named",
            ],
            "{\"a\":\"1\",\"b\":\"2\"}\n",
            0,
        ),
    ];
    for &(args, expected, code) in rows {
        let (stdout, stderr, exit) = run_jq_full(args, None)?;
        assert_eq!(
            (stdout.as_str(), exit),
            (expected, code),
            "jq {args:?}: stderr {stderr:?}"
        );
    }
    Ok(())
}
