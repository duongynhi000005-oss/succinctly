//! #4971: `bsearch`, `combinations`, `fromstream` and `truncate_stream` follow jq's own definitions on inputs a type check
//! would refuse.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// jq writes these builtins in jq: `bsearch` and `combinations` open with `if length == 0`, `fromstream` and
// `truncate_stream` read each event through `length`, `.[0]` and a slice, and `truncate_stream` runs its stream on
// `null` (`. as $n | null | stream | ..`). Those are total over every type, so `0 | bsearch(1)` is `-1`, `null |
// combinations` is `[]`, `null | fromstream(.)` is empty and `1 | truncate_stream([1])` is empty, where the binary
// refused with its own `requires array`/`Invalid streaming format` for any input that was not the usual shape.
// Every row captured from `/usr/bin/jq` 1.7.1 (stdout, error message, exit code), both routes.

/// #4971: the rows of a 720-row program x input grid that differed on `main`, every fourth plus one per program, and
/// controls that matched before.
#[test]
fn test_4971_builtins_follow_jqs_definitions_on_atypical_inputs() -> Result<()> {
    assert_path_rows_both_routes_3749(&[
        (
            r"true",
            r"bsearch(1)",
            "",
            r"boolean (true) has no length",
            5,
        ),
        (
            r"-1",
            r"bsearch(1)",
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r#""abc""#,
            r"bsearch(1)",
            "",
            r"Cannot index string with number",
            5,
        ),
        (
            r#"{"a":1}"#,
            r"bsearch(1)",
            "",
            r"Cannot index object with number",
            5,
        ),
        (
            r"true",
            r"bsearch(null)",
            "",
            r"boolean (true) has no length",
            5,
        ),
        (r"0", r"bsearch(null)", "-1\n", "", 0),
        (
            r"1.5",
            r"bsearch(null)",
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r#""a""#,
            r"bsearch(null)",
            "",
            r"Cannot index string with number",
            5,
        ),
        (
            r"true",
            r#"bsearch("a")"#,
            "",
            r"boolean (true) has no length",
            5,
        ),
        (
            r"-1",
            r#"bsearch("a")"#,
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r#""abc""#,
            r#"bsearch("a")"#,
            "",
            r"Cannot index string with number",
            5,
        ),
        (
            r#"{"a":1}"#,
            r#"bsearch("a")"#,
            "",
            r"Cannot index object with number",
            5,
        ),
        (
            r"true",
            r"bsearch([1])",
            "",
            r"boolean (true) has no length",
            5,
        ),
        (r"0", r"bsearch([1])", "-1\n", "", 0),
        (
            r"1.5",
            r"bsearch([1])",
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r#""a""#,
            r"bsearch([1])",
            "",
            r"Cannot index string with number",
            5,
        ),
        (
            r"true",
            r"bsearch((1,2))",
            "",
            r"boolean (true) has no length",
            5,
        ),
        (
            r"-1",
            r"bsearch((1,2))",
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r#""abc""#,
            r"bsearch((1,2))",
            "",
            r"Cannot index string with number",
            5,
        ),
        (
            r#"{"a":1}"#,
            r"bsearch((1,2))",
            "",
            r"Cannot index object with number",
            5,
        ),
        (r"null", r"combinations", "[]\n", "", 0),
        (
            r"false",
            r"combinations",
            "",
            r"boolean (false) has no length",
            5,
        ),
        (
            r"2",
            r"combinations",
            "",
            r"Cannot index number with number",
            5,
        ),
        (r#""""#, r"combinations", "[]\n", "", 0),
        (
            r"[null]",
            r"combinations",
            "",
            r"Cannot iterate over null (null)",
            5,
        ),
        (r#"[{"a":1},[2]]"#, r"combinations", "[1,2]\n", "", 0),
        (r"null", r"combinations(0)", "[]\n", "", 0),
        (r"false", r"combinations(0)", "[]\n", "", 0),
        (r"2", r"combinations(0)", "[]\n", "", 0),
        (r#""""#, r"combinations(0)", "[]\n", "", 0),
        (r#"{"a":[1,2]}"#, r"combinations(0)", "[]\n", "", 0),
        (
            r"null",
            r"combinations(1)",
            "",
            r"Cannot iterate over null (null)",
            5,
        ),
        (
            r"0",
            r"combinations(1)",
            "",
            r"Cannot iterate over number (0)",
            5,
        ),
        (
            r"1.5",
            r"combinations(1)",
            "",
            r"Cannot iterate over number (1.5)",
            5,
        ),
        (
            r#""a""#,
            r"combinations(1)",
            "",
            r#"Cannot iterate over string ("a")"#,
            5,
        ),
        (
            r"null",
            r"combinations(2)",
            "",
            r"Cannot iterate over null (null)",
            5,
        ),
        (
            r"1",
            r"combinations(2)",
            "",
            r"Cannot iterate over number (1)",
            5,
        ),
        (
            r"-0.5",
            r"combinations(2)",
            "",
            r"Cannot iterate over number (-0.5)",
            5,
        ),
        (r"{}", r"combinations(2)", "", "", 0),
        (r"null", r"combinations(empty)", "[]\n", "", 0),
        (r"true", r"combinations(empty)", "[]\n", "", 0),
        (r"-1", r"combinations(empty)", "[]\n", "", 0),
        (r#""abc""#, r"combinations(empty)", "[]\n", "", 0),
        (r#"{"a":1}"#, r"combinations(empty)", "[]\n", "", 0),
        (
            r"null",
            r"combinations((1,2))",
            "",
            r"Cannot iterate over null (null)",
            5,
        ),
        (
            r"false",
            r"combinations((1,2))",
            "",
            r"Cannot iterate over boolean (false)",
            5,
        ),
        (
            r"2",
            r"combinations((1,2))",
            "",
            r"Cannot iterate over number (2)",
            5,
        ),
        (
            r#""""#,
            r"combinations((1,2))",
            "",
            r#"Cannot iterate over string ("")"#,
            5,
        ),
        (
            r#"{"a":[1,2]}"#,
            r"combinations((1,2))",
            "[[1,2],[1,2],[1,2]]\n",
            "",
            0,
        ),
        (r"null", r"fromstream(.)", "", "", 0),
        (
            r"0",
            r"fromstream(.)",
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r"1.5",
            r"fromstream(.)",
            "",
            r"Cannot index number with number",
            5,
        ),
        (
            r#""a""#,
            r"fromstream(.)",
            "",
            r"Cannot index string with number",
            5,
        ),
        (r"[null]", r"fromstream(.)", "", "", 0),
        (
            r#"[{"a":1},[2]]"#,
            r"fromstream(.)",
            "",
            r#"array (["x"]) and object ({"a":1}) cannot be added"#,
            5,
        ),
        (
            r"[1]",
            r"fromstream(.[]?)",
            "",
            r"Cannot index number with number",
            5,
        ),
        (r"[[1],[2]]", r"fromstream(.[]?)", "null\n", "", 0),
        (
            r#"{"a":[1,2]}"#,
            r"fromstream(.[]?)",
            "",
            r#"array (["x"]) and number (1) cannot be added"#,
            5,
        ),
        (r"null", r"fromstream([1])", "null\n", "", 0),
        (r"1", r"fromstream([1])", "null\n", "", 0),
        (r"-0.5", r"fromstream([1])", "null\n", "", 0),
        (r"[]", r"fromstream([1])", "null\n", "", 0),
        (r"[[]]", r"fromstream([1])", "null\n", "", 0),
        (r#"{"a":[1,2]}"#, r"fromstream([1])", "null\n", "", 0),
        (r"null", r"truncate_stream(.)", "[null]\n", "", 0),
        (r"1", r"truncate_stream(.)", "", "", 0),
        (r"-0.5", r"truncate_stream(.)", "[null]\n", "", 0),
        (r"[]", r"truncate_stream(.)", "", "", 0),
        (r"{}", r"truncate_stream(.)", "", "", 0),
        (r"[1,[2,3]]", r"truncate_stream(.)", "", "", 0),
        (
            r"null",
            r"truncate_stream([1])",
            "",
            r"Cannot index number with object",
            5,
        ),
        (
            r"0",
            r"truncate_stream([1])",
            "",
            r"Cannot index number with object",
            5,
        ),
        (r"1.5", r"truncate_stream([1])", "", "", 0),
        (r#""a""#, r"truncate_stream([1])", "", "", 0),
        (r"[[1],[2]]", r"truncate_stream([1])", "", "", 0),
        (r#"{"a":1}"#, r"truncate_stream([1])", "", "", 0),
        (r"[1,[2,3]]", r"truncate_stream([1])", "", "", 0),
        (
            r"true",
            r"truncate_stream([[0],1])",
            "",
            r"Array/string slice indices must be integers",
            5,
        ),
        (
            r"true",
            r"truncate_stream([[0],1],[[1,0],2],[[1,0]],[[1]])",
            "",
            r"Array/string slice indices must be integers",
            5,
        ),
        (
            r"false",
            r"truncate_stream([[0],1],[[1,0],2],[[1,0]],[[1]])",
            "",
            r"Array/string slice indices must be integers",
            5,
        ),
        (r"[1]", r".|truncate_stream(.[]?)", "", "", 0),
        (r"[1,2,3]", r".|truncate_stream(.[]?)", "", "", 0),
        (r#"{"a":1}"#, r".|truncate_stream(.[]?)", "", "", 0),
        (r"[1,[2,3]]", r".|truncate_stream(.[]?)", "", "", 0),
        (r"[1,2,3]", r"bsearch(1)", "0\n", "", 0),
        (r"[1,2,3]", r"bsearch(5)", "-4\n", "", 0),
        (r"null", r"bsearch(null)", "-1\n", "", 0),
        (
            r"[[1,2],[3,4]]",
            r"combinations",
            "[1,3]\n[1,4]\n[2,3]\n[2,4]\n",
            "",
            0,
        ),
        (
            r"[0,1]",
            r"combinations(2)",
            "[0,0]\n[0,1]\n[1,0]\n[1,1]\n",
            "",
            0,
        ),
        (r"[]", r"combinations", "[]\n", "", 0),
        (r"[[],[1]]", r"combinations", "", "", 0),
        (
            r#"{"a":[1,{"b":2}]}"#,
            r"fromstream(tostream)",
            "{\"a\":[1,{\"b\":2}]}\n",
            "",
            0,
        ),
        (
            r"null",
            r"fromstream(1|truncate_stream([[0],1],[[1,0],2],[[1,0]],[[1]]))",
            "[2]\n",
            "",
            0,
        ),
        (
            r"1",
            r"truncate_stream([[0],1],[[1,0],2],[[1,0]],[[1]])",
            "[[0],2]\n[[0]]\n",
            "",
            0,
        ),
    ])
}
