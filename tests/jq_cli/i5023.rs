//! #5023: a `foreach` UPDATE that is a pipe of no-ops (`.|.`) over an untracked state hands it on as a bare `.` does.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// `push_path_components` drops every `Identity`, so `(.|.)` flattened to nothing and `resolve_static_tail` raised #530's
// "with result" refusal on the untracked state. That is the terminal's check of a value that is not the register; a
// fold's UPDATE stores its output unchecked, so `foreach (.) as $i (null; (.|.); $x)` was refused (and `[path(..)?]`
// dropped the path) where jq answers from the EXTRACT, as it does for a lone `.`.

/// #5023: `(.|.)`, `(.|.|.)`, a comma sibling of one, and `try`/`?` around one as the UPDATE, over an INIT that is
/// `null`, a number and `[]`, under a `$x` or `$i` EXTRACT; `[path(..)?]`, `try path(..) catch`, `try del(..) catch`.
/// The last rows are the terminal's own refusals, which stay: `path(1 | .)`, `path(null | (.|.))`. Every row captured
/// from `/usr/bin/jq` 1.7.1 (stdout, first stderr line up to the container, exit code), both routes.
#[test]
#[allow(clippy::literal_string_with_formatting_args)] // jq object patterns read like format arguments
