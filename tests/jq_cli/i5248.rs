//! #5248: `..` followed by a bracket suffix (`..[0]?`, `..[]?`, `..["a"]?`, `..[1:]?`) is a postfix on the
//! `..` term in jq mode, as it is in jq 1.7.1; it was a parse error here. yq's lexer rejects the same
//! spellings (`Error: bad expression`), so yq mode keeps rejecting them.
//!
//! The interpreter reads storage identity, which the `unshared-containers` holdout does not have, so the
//! path rows pin the shipped shape only.
#![cfg(not(feature = "unshared-containers"))]

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

/// Every row captured from `/usr/bin/jq` 1.7.1 (stdout, first error message, exit code), as a read
/// and in `path`, `del`, `|=` and `=` contexts, on both routes.
#[test]
#[allow(clippy::literal_string_with_formatting_args)] // jq object patterns read like format arguments
fn test_recursive_descent_bracket_suffix_matches_jq_5248() -> Result<()> {
    assert_path_rows_both_routes_3749(&[
        (r#"[[1,{"a":2}]]"#, r"[..[0]?]", "[[1,{\"a\":2}],1]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(..[0]?)]", "[[0],[0,0]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"del(..[0]?)", "[]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(..[0]?) |= 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"(..[0]?) = 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"[..[]?]", "[[1,{\"a\":2}],1,{\"a\":2},2]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(..[]?)]", "[[0],[0,0],[0,1],[0,1,\"a\"]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"del(..[]?)", "[]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(..[]?) |= 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"(..[]?) = 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r#"[..["a"]?]"#, "[2]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r#"[path(..["a"]?)]"#, "[[0,1,\"a\"]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r#"del(..["a"]?)"#, "[[1,{}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r#"(..["a"]?) |= 9"#, "[[1,{\"a\":9}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r#"(..["a"]?) = 9"#, "[[1,{\"a\":9}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[..[1:]?]", "[[],[{\"a\":2}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(..[1:]?)]", "[[{\"start\":1,\"end\":null}],[0,{\"start\":1,\"end\":null}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"del(..[1:]?)", "[[1]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(..[1:]?) |= 9", "", "A slice of an array can only be assigned another array", 5),
        (r#"[[1,{"a":2}]]"#, r"(..[1:]?) = 9", "", "A slice of an array can only be assigned another array", 5),
        (r#"[[1,{"a":2}]]"#, r"[.. [0]?]", "[[1,{\"a\":2}],1]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(.. [0]?)]", "[[0],[0,0]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"del(.. [0]?)", "[]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(.. [0]?) |= 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"(.. [0]?) = 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"[.. .a?]", "[2]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(.. .a?)]", "[[0,1,\"a\"]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"del(.. .a?)", "[[1,{}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(.. .a?) |= 9", "[[1,{\"a\":9}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(.. .a?) = 9", "[[1,{\"a\":9}]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[..[0][0]?]", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"[path(..[0][0]?)]", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"del(..[0][0]?)", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"(..[0][0]?) |= 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"(..[0][0]?) = 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"[..[-1]?]", "[[1,{\"a\":2}],{\"a\":2}]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(..[-1]?)]", "[[-1],[0,-1]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"del(..[-1]?)", "[]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"(..[-1]?) |= 9", "", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r"(..[-1]?) = 9", "", "Cannot index number with number", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[..[0]?]", "[1,null]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[path(..[0]?)]", "[[\"a\",0],[\"a\",1,\"b\",0]]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"del(..[0]?)", "{\"a\":[{\"b\":null}],\"c\":\"x\"}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[0]?) |= 9", "{\"a\":[9,{\"b\":[9]}],\"c\":\"x\"}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[0]?) = 9", "{\"a\":[9,{\"b\":[9]}],\"c\":\"x\"}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[..[]?]", "[[1,{\"b\":null}],\"x\",1,{\"b\":null},null]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[path(..[]?)]", "[[\"a\"],[\"c\"],[\"a\",0],[\"a\",1],[\"a\",1,\"b\"]]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"del(..[]?)", "{}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[]?) |= 9", "", "Cannot index number with number", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[]?) = 9", "", "Cannot index number with number", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r#"[..["a"]?]"#, "[[1,{\"b\":null}],null,null]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r#"[path(..["a"]?)]"#, "[[\"a\"],[\"a\",1,\"a\"],[\"a\",1,\"b\",\"a\"]]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r#"del(..["a"]?)"#, "{\"c\":\"x\"}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r#"(..["a"]?) |= 9"#, "", "Cannot index number with number", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r#"(..["a"]?) = 9"#, "", "Cannot index number with number", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[..[1:]?]", "[[{\"b\":null}],null,\"\"]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[path(..[1:]?)]", "[[\"a\",{\"start\":1,\"end\":null}],[\"a\",1,\"b\",{\"start\":1,\"end\":null}],[\"c\",{\"start\":1,\"end\":null}]]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"del(..[1:]?)", "", "Cannot delete fields from string", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[1:]?) |= 9", "", "A slice of an array can only be assigned another array", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[1:]?) = 9", "", "A slice of an array can only be assigned another array", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[..[0]?[0]?]", "[null]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[path(..[0]?[0]?)]", "[[\"a\",1,\"b\",0,0]]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"del(..[0]?[0]?)", "{\"a\":[1,{\"b\":null}],\"c\":\"x\"}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[0]?[0]?) |= 9", "{\"a\":[1,{\"b\":[[9]]}],\"c\":\"x\"}\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"(..[0]?[0]?) = 9", "{\"a\":[1,{\"b\":[[9]]}],\"c\":\"x\"}\n", "", 0),
        (r"[[[1]]]", r"[..[0]?]", "[[[1]],[1],1]\n", "", 0),
        (r"[[[1]]]", r"[path(..[0]?)]", "[[0],[0,0],[0,0,0]]\n", "", 0),
        (r"[[[1]]]", r"del(..[0]?)", "[]\n", "", 0),
        (r"[[[1]]]", r"(..[0]?) |= 9", "", "Cannot index number with number", 5),
        (r"[[[1]]]", r"(..[0]?) = 9", "", "Cannot index number with number", 5),
        (r"[[[1]]]", r"[..[0:1]?]", "[[[[1]]],[[1]],[1]]\n", "", 0),
        (r"[[[1]]]", r"[path(..[0:1]?)]", "[[{\"start\":0,\"end\":1}],[0,{\"start\":0,\"end\":1}],[0,0,{\"start\":0,\"end\":1}]]\n", "", 0),
        (r"[[[1]]]", r"del(..[0:1]?)", "[]\n", "", 0),
        (r"[[[1]]]", r"(..[0:1]?) |= 9", "", "A slice of an array can only be assigned another array", 5),
        (r"[[[1]]]", r"(..[0:1]?) = 9", "", "A slice of an array can only be assigned another array", 5),
        (r#"{"a":{"a":{"a":1}}}"#, r#"[..["a"]?]"#, "[{\"a\":{\"a\":1}},{\"a\":1},1]\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r#"[path(..["a"]?)]"#, "[[\"a\"],[\"a\",\"a\"],[\"a\",\"a\",\"a\"]]\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r#"del(..["a"]?)"#, "{}\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r#"(..["a"]?) |= 9"#, "", "Cannot index number with string \"a\"", 5),
        (r#"{"a":{"a":{"a":1}}}"#, r#"(..["a"]?) = 9"#, "", "Cannot index number with string \"a\"", 5),
        (r#"{"a":{"a":{"a":1}}}"#, r"[..[]?]", "[{\"a\":{\"a\":1}},{\"a\":1},1]\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r"[path(..[]?)]", "[[\"a\"],[\"a\",\"a\"],[\"a\",\"a\",\"a\"]]\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r"del(..[]?)", "{}\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r"(..[]?) |= 9", "", "Cannot index number with string \"a\"", 5),
        (r#"{"a":{"a":{"a":1}}}"#, r"(..[]?) = 9", "", "Cannot index number with string \"a\"", 5),
        (r#"[[1,{"a":2}]]"#, r"..[0]", "[1,{\"a\":2}]\n1\n", "Cannot index number with number", 5),
        (r#"[[1,{"a":2}]]"#, r#"try path(..[0]) catch "E""#, "[0]\n[0,0]\n\"E\"\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r"[path(..[0]?)]", "[[0],[0,0]]\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"..[0]", "", "Cannot index object with number", 5),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r#"try path(..[0]) catch "E""#, "\"E\"\n", "", 0),
        (r#"{"a":[1,{"b":null}],"c":"x"}"#, r"[path(..[0]?)]", "[[\"a\",0],[\"a\",1,\"b\",0]]\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r#"..["a"]"#, "", "Cannot index array with string \"a\"", 5),
        (r#"[[1,{"a":2}]]"#, r#"try path(..["a"]) catch "E""#, "\"E\"\n", "", 0),
        (r#"[[1,{"a":2}]]"#, r#"[path(..["a"]?)]"#, "[[0,1,\"a\"]]\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r#"..["a"]"#, "{\"a\":{\"a\":1}}\n{\"a\":1}\n1\n", "Cannot index number with string \"a\"", 5),
        (r#"{"a":{"a":{"a":1}}}"#, r#"try path(..["a"]) catch "E""#, "[\"a\"]\n[\"a\",\"a\"]\n[\"a\",\"a\",\"a\"]\n\"E\"\n", "", 0),
        (r#"{"a":{"a":{"a":1}}}"#, r#"[path(..["a"]?)]"#, "[[\"a\"],[\"a\",\"a\"],[\"a\",\"a\",\"a\"]]\n", "", 0),
    ])
}
