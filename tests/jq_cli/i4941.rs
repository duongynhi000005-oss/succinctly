//! #4941: a stage that hands its input on once ahead of a destructure of `.` inside `[ .. ]`, in a fold nested in a
//! `reduce` UPDATE.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

/// #4941: in the body of a `reduce` whose source moved jq's register onto an element, `.` is not the register,
/// so a destructure of it raises `near attempt to access element "b" of <accumulator>`, also behind a stage that
/// only hands its input on (`select(true)`, `first(.)`, `limit(2; .)`, `(.)?`) inside the brackets of a nested
/// fold's source. The binary read `[ .. ]` with such a stage as opaque and answered (`path(..)` printed `[]`,
/// `del(..)` deleted the document, `|= 9` replaced it). A stage that can empty its input (`select(false)`) is
/// the control: the destructure is never reached and jq answers. Rows are a sample (ten per source shape) of
/// the fold-body grid's new `wrapped-sel-*`/`wrapped-first-dot`/`wrapped-limit-dot`/`wrapped-opt-dot` sources
/// over the `rd-nav`, `rd-nava`, `rd-rec` and `rd-lit` outers; every one captured from `/usr/bin/jq` 1.7.1, both routes.
#[test]
